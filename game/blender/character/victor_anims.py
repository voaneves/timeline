def render_40s_turntable(armature: bpy.types.Object, specs: list[dict]) -> dict:
    """Render a 40 s (960 frames @ 24 fps, 1280x720) Eevee turntable of all 18 clips."""
    scene = bpy.context.scene
    rig = vn_scene.add_preview_rig(
        target=(0.0, 0.0, 0.58),
        radius=0.85,
        collection_name="_PreviewRig",
        engine_coords=False,
    )
    cam = rig["camera"]
    tgt = Vector((0.0, 0.0, 0.58))
    dist = 2.45

    os.makedirs(TURNTABLE_FRAMES_DIR, exist_ok=True)
    os.makedirs(PREVIEW_DIR, exist_ok=True)

    scene.render.engine = vn_scene.detect_eevee_engine(scene)
    if hasattr(scene, "eevee") and hasattr(scene.eevee, "taa_render_samples"):
        scene.eevee.taa_render_samples = 8
    scene.render.resolution_x = 1280
    scene.render.resolution_y = 720
    scene.render.resolution_percentage = 100
    scene.render.fps = 24
    scene.render.image_settings.file_format = "PNG"
    scene.render.image_settings.color_mode = "RGB"

    tracks_by_name = {t.name: t for t in armature.animation_data.nla_tracks}
    total_frames = 960
    # Distribute 960 frames across 18 clips (~53 frames each, 60 on idle)
    counts = [60] + [53] * 14 + [52] * 3  # 60 + 14*53 + 3*52 = 958... wait: 60 + 17*53 = 961 -> 59 + 17*53 = 960!
    counts = [59] + [53] * 17  # sum = 59 + 901 = 960

    frame_idx = 0
    try:
        for spec, seg_len in zip(specs, counts):
            clip_name = spec["name"]
            clip_frames = int(spec["frame_count"])
            is_loop = bool(spec["loop"])

            for t in armature.animation_data.nla_tracks:
                t.mute = True
            tracks_by_name[clip_name].mute = False

            for local_f in range(seg_len):
                if is_loop:
                    eval_f = local_f % max(clip_frames, 1)
                else:
                    # Play once, hold last pose briefly, or repeat cleanly within 2.2 s window
                    eval_f = local_f % (clip_frames + 8)
                    if eval_f > clip_frames:
                        eval_f = clip_frames

                scene.frame_set(int(eval_f))
                angle = (2.0 * math.pi * frame_idx) / float(total_frames)
                # Orbit smoothly around Victor starting from front-3/4 (-Y)
                yaw = -math.pi * 0.5 + 0.35 + angle
                cam.location = tgt + Vector((
                    math.cos(yaw) * dist,
                    math.sin(yaw) * dist,
                    0.50,
                ))
                vn_scene._look_at(cam, tgt)

                scene.render.filepath = os.path.join(
                    TURNTABLE_FRAMES_DIR, f"frame_{frame_idx:04d}.png"
                )
                bpy.ops.render.render(write_still=True)
                frame_idx += 1
    finally:
        for t in armature.animation_data.nla_tracks:
            t.mute = False
        vn_rig.reset_pose(armature)
        vn_scene._remove_preview_rig(rig)

    ffmpeg = _find_ffmpeg()
    abs_mp4 = os.path.abspath(TURNTABLE_MP4)
    cmd = [
        ffmpeg,
        "-y",
        "-framerate",
        "24",
        "-i",
        os.path.join(TURNTABLE_FRAMES_DIR, "frame_%04d.png"),
        "-c:v",
        "libx264",
        "-pix_fmt",
        "yuv420p",
        "-crf",
        "20",
        "-movflags",
        "+faststart",
        abs_mp4,
    ]
    proc = subprocess.run(cmd, capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise RuntimeError(f"ffmpeg failed ({proc.returncode}): {proc.stderr}")

    print(f"[T2.8d] Rendered {frame_idx} frames -> {abs_mp4}")
    return {"mp4": abs_mp4, "frames": frame_idx, "fps": 24, "duration_s": frame_idx / 24.0}


