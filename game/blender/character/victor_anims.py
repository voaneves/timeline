def _ensure_rigged_scene() -> tuple[bpy.types.Object, bpy.types.Collection]:
    """Load `victor_rigged.blend` if present, or rebuild via `victor_rig`."""
    if os.path.exists(RIGGED_BLEND):
        bpy.ops.wm.open_mainfile(filepath=os.path.abspath(RIGGED_BLEND))
    else:
        vr.build_rigged_victor()

    arm = bpy.data.objects.get("VictorArmature")
    if arm is None:
        raise RuntimeError("VictorArmature not found after loading/building rigged Victor")
    col = arm.users_collection[0] if arm.users_collection else bpy.context.scene.collection
    return arm, col


def build_victor_animations(render_turntable: bool = False) -> dict:
    """Create all 18 NLA clips, export animated/core/extras GLBs, and optionally render turntable."""
    arm, col = _ensure_rigged_scene()
    specs = _clip_specs()
    clips_meta = []
    for spec in specs:
        meta = vn_anim.create_clip(armature=arm, **spec)
        clips_meta.append(meta)

    os.makedirs(OUT_DIR, exist_ok=True)

    full_info = vn_anim.export_nla_subset(
        armature=arm,
        clip_names=ALL_CLIPS,
        filepath=ANIMATED_GLB,
        collections=[col],
        fps=24,
    )
    core_info = vn_anim.export_nla_subset(
        armature=arm,
        clip_names=CORE_CLIPS,
        filepath=CORE_GLB,
        collections=[col],
        fps=24,
    )
    extras_info = vn_anim.export_nla_subset(
        armature=arm,
        clip_names=EXTRAS_CLIPS,
        filepath=EXTRAS_GLB,
        collections=[col],
        fps=24,
    )

    full_anims = [a.get("name") for a in full_info["gltf"].get("animations", [])]
    core_anims = [a.get("name") for a in core_info["gltf"].get("animations", [])]
    extras_anims = [a.get("name") for a in extras_info["gltf"].get("animations", [])]

    print(
        f"[T2.7-T2.8] Exported 18 clips -> animated={full_info['bytes']} B ({len(full_anims)} anims), "
        f"core={core_info['bytes']} B ({len(core_anims)} anims), "
        f"extras={extras_info['bytes']} B ({len(extras_anims)} anims)"
    )

    turntable_info = None
    if render_turntable:
        turntable_info = render_40s_turntable(arm, specs)

    return {
        "clips": [m["name"] for m in clips_meta],
        "full_anims": full_anims,
        "core_anims": core_anims,
        "extras_anims": extras_anims,
        "full_bytes": full_info["bytes"],
        "core_bytes": core_info["bytes"],
        "extras_bytes": extras_info["bytes"],
        "turntable": turntable_info,
    }


